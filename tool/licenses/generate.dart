import 'dart:convert';
import 'dart:io';

const _out = 'lib/src/app/runtime_packages.dart';

void main() {
  final result = Process.runSync('dart', [
    'pub',
    'deps',
    '--json',
  ], runInShell: Platform.isWindows);
  if (result.exitCode != 0) {
    stderr.write(result.stderr);
    exit(result.exitCode);
  }
  final deps = jsonDecode(result.stdout as String) as Map<String, dynamic>;
  final packages = {
    for (final p in deps['packages'] as List<dynamic>)
      (p as Map<String, dynamic>)['name'] as String: p,
  };
  List<String> names(Object? list) => [
    for (final name in list as List<dynamic>? ?? const <dynamic>[])
      name as String,
  ];

  final root = deps['root'] as String;
  final runtime = <String>{};
  final pending = [root];
  while (pending.isNotEmpty) {
    final name = pending.removeLast();
    if (!runtime.add(name)) continue;
    final package = packages[name]!;
    pending.addAll(
      names(
        name == root ? package['directDependencies'] : package['dependencies'],
      ),
    );
  }
  final dev = packages.keys.toSet().difference(runtime);

  String set(String name, Set<String> values) =>
      'const $name = <String>{\n'
      '${[for (final v in values.toList()..sort()) "  '$v',\n"].join()}'
      '};\n';
  File(_out).writeAsStringSync(
    '// Generated by tool/licenses/generate.dart; do not edit.\n'
    '\n'
    '/// The pub packages the app runs with.\n'
    '${set('runtimePackages', runtime)}'
    '\n'
    '/// The pub packages only development needs (tests, codegen, icons).\n'
    '${set('devPackages', dev)}',
  );
}
